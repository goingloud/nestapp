function steps = stepRegistry()
% STEPREGISTRY  Returns metadata for all nestapp pipeline steps.
%
%   steps = stepRegistry() returns a 1-by-N struct array. Each element:
%     .name      - exact string matching the switch case in runPipelineCore.m
%                  and the StepsListBox item in nestapp.m
%     .defaults  - struct of default parameter values
%     .info      - description shown in the Info panel
%     .params    - struct array of per-field metadata:
%                    .key          raw field name (must match dispatchStep switch/case)
%                    .friendlyName display label shown in UITable
%                    .unit         unit string ('Hz', 'ms', 's', 'uV', '' ...)
%                    .validRange   string describing valid input ('on|off', '[0 Inf]', ...)
%                    .description  one-line tooltip
%                    .type         'scalar'|'integer'|'vector'|'logical'|'string'|'stringlist'
%
%   To add a step: append one block below, then add the matching case
%   in runPipelineCore.m.
%
% Copyright (C) 2023  Aref Pariz, University of Ottawa & The Royal
% Institute for Mental Health, Ottawa, Ontario, Canada.

% Persistent cache: stepRegistry() is called from startupFcn, LoadPipeline,
% and LoadTemplate - avoid rebuilding the full struct array on every call.
persistent cachedSteps
if ~isempty(cachedSteps)
    steps = cachedSteps;
    return
end

steps = struct('name',{},'defaults',{},'info',{},'params',{},'requires',{}, ...
    'exclusiveParamGroups',{},'paramEnableWhen',{},'interactive',{}, ...
    'interactiveWhen',{},'listed',{});

