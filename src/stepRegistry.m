    '.cnt (Neuroscan), .cdt (Curry).'];
s.params = makeParam('redraw','Redraw EEGLAB','','on|off', ...
    'Update the EEGLAB GUI window after loading.', 'type', 'logical');
s.requires = [ ...
    req('pop_loadbv',  'bva-io',  'EEGLAB Plugin Manager -> search "bva-io"',   '.vhdr'), ...
    req('pop_loadcnt', 'loadcnt', 'EEGLAB Plugin Manager -> search "loadcnt"',  '.cnt'), ...
    req('loadcurry',   'curry',   'EEGLAB Plugin Manager -> search "curry"',    '.cdt')];
