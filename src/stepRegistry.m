function s = blankStep()
% Returns an empty step struct with correct field names.
s = struct('name','','defaults',struct(),'info','','params',struct([]),'requires',struct([]));
% Param-relationship metadata (both optional / empty by default). See
% disabledParamKeys for how these grey out and lock params in the GUI.
%   exclusiveParamGroups - cell of ordered key-lists; only one member of each
%                          group may hold a value (index 1 = precedence).
%   paramEnableWhen      - rules struct array; a param is disabled unless its
%                          controlling param holds one of the listed values.
s.exclusiveParamGroups = {};
s.paramEnableWhen      = struct('param', {}, 'controller', {}, 'values', {});
% interactive - the step blocks waiting for a human (a modal, a rejection
% menu, a plot the user closes). Such a step cannot run on a parallel worker:
% workers get uiFigure = [] and have no display, so the run either errors on
% every file or blocks with nothing to click. The app checks this before a run
% and offers to turn parallel off - see interactivePipelineSteps.
s.interactive = false;
% interactiveWhen - the step blocks only for certain parameter values, e.g.
% TESA compselect's manual review. Same shape as paramEnableWhen. A step is
% treated as interactive if `interactive` is true OR any of these rules match
% the parameters it is configured with.
%
% This cannot be detected by scanning the dispatch: the blocking call lives
% inside the wrapped third-party function, not in nestapp's case body. It has
% to be declared.
s.interactiveWhen = struct('param', {}, 'values', {});
% listed - whether the step appears in the picker at all. false for steps that
% are not free-standing: the AARATEP orchestrator is a whole pipeline and
% arrives only with its template, so offering it as a step to drop anywhere
% would be a lie about what it is. See availableSteps.
s.listed = true;
end

function r = req(fn, plugin, installNote, fileExt, feature, minVersion)
% req  Build one dependency requirement struct.
%   fn          - function name to probe with which() (e.g. 'pop_loadbv')
%   plugin      - display name shown in error messages (e.g. 'bva-io')
%   installNote - one-line install instruction for the user
%   fileExt     - (optional) only check when input files have this extension
%                 (e.g. '.vhdr'). Empty string '' means always check.
%   feature     - (optional) license feature name for a toolbox function
%                 (e.g. 'Curve_Fitting_Toolbox'). When set, stepAvailability
%                 uses a stronger probe than which(), because a class-method
%                 fallthrough (e.g. @gmdistribution/fit) leaves which('fit')
%                 non-empty even when the real toolbox fit() is gone.
%   minVersion  - (optional) minimum plugin version, e.g. '1.2'. The step is
%                 hidden from the picker and blocks a run when the installed
%                 plugin declares less. Read from the plugin's own version
%                 declaration - never inferred from whether the function
%                 happens to be on the path, which a vendored copy can fake.
if nargin < 4; fileExt    = ''; end
if nargin < 5; feature    = ''; end
if nargin < 6; minVersion = ''; end
r = struct('fn', fn, 'plugin', plugin, 'installNote', installNote, ...
    'fileExt', fileExt, 'feature', feature, 'minVersion', minVersion);
end

function p = makeParam(key, friendlyName, unit, validRange, description, varargin)
% makeParam  Make a parameter metadata struct.
%   Optional name-value pairs: 'placeholder' (shown in UITable for [] values, e.g.
%   '(all channels)') and 'type': scalar (default) | integer | vector | logical | string | stringlist
placeholder = ''; type = 'scalar';
if mod(numel(varargin), 2) ~= 0
    error('makeParam:oddArgs', 'Name-value arguments must come in pairs.');
end
for i = 1:2:numel(varargin)
    switch lower(varargin{i})
        case 'placeholder'; placeholder = varargin{i+1};
        case 'type';        type = varargin{i+1};
        otherwise
            error('makeParam:unknownOpt', 'Unknown option "%s".', varargin{i});
    end
end
p = struct('key',key,'friendlyName',friendlyName,'unit',unit, ...
           'validRange',validRange,'description',description, ...
           'placeholder',placeholder,'type',type);
end

